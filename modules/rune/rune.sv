            {7'd126, 3'd4}: get_glyph = 8'h00;
            {7'd126, 3'd5}: get_glyph = 8'h00;
            {7'd126, 3'd6}: get_glyph = 8'h00;
            {7'd126, 3'd7}: get_glyph = 8'h00;
            default: get_glyph = 8'hFF;
        endcase
    endfunction

    wire [7:0] glyph_data = get_glyph(char_code, row_idx);

    wire [3:0] pixel_count = glyph_data[0] + glyph_data[1] + glyph_data[2] + glyph_data[3] +
                              glyph_data[4] + glyph_data[5] + glyph_data[6] + glyph_data[7];

    always_ff @(posedge clk) begin
        reg_ready <= 1'b0;
        if (rst) begin
            char_code <= 7'd32; row_idx <= 3'd0;
        end else begin
            if (reg_wr) begin
                reg_ready <= 1'b1;
                case (reg_addr[4:2])
                    3'h0: char_code <= reg_wdata[6:0];
                    3'h1: row_idx <= reg_wdata[2:0];
                endcase
            end
            if (reg_rd) begin
                reg_ready <= 1'b1;
                case (reg_addr[4:2])
                    3'h2: reg_rdata <= {24'd0, glyph_data};
                    3'h3: reg_rdata <= {28'd0, pixel_count};
                    default: reg_rdata <= 32'd0;
                endcase
            end
        end
    end
endmodule
